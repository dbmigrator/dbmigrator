use handlebars::Handlebars;
use pgarchive::{Archive, TocEntry};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::LazyLock;

#[derive(Debug, Clone, Deserialize)]
pub struct PgDdlRule {
    #[serde(default)]
    pub empty_namespace: bool,
    pub desc_pattern: Option<String>,
    pub tag_pattern: Option<String>,
    pub filename: String,
}

#[derive(Debug, Clone, Serialize)]
struct TemplateData {
    namespace: String,
    desc_parts: Vec<String>,
    tag_parts: Vec<String>,
}

#[derive(Debug)]
struct PgDdlMatcher {
    empty_namespace: bool,
    desc_regex: regex::Regex,
    tag_regex: regex::Regex,
    filename_template: String,
}

impl PgDdlMatcher {
    fn new(handlebars: &mut Handlebars, rule: &PgDdlRule) -> Result<Self, regex::Error> {
        let desc_pattern = rule.desc_pattern.as_deref().unwrap_or(".*");
        let desc_pattern = desc_pattern.replace("{name}", r#"([[:word:]-]+|\"[[:word:]- ]+\")"#);
        let desc_regex = regex::Regex::new(&desc_pattern)?;
        let tag_pattern = rule.tag_pattern.as_deref().unwrap_or(".*");
        let tag_pattern = tag_pattern.replace("{name}", r#"([[:word:]-]+|\"[[:word:]- ]+\")"#);
        let tag_regex = regex::Regex::new(&tag_pattern)?;
        handlebars
            .register_template_string(&rule.filename, &rule.filename)
            .unwrap();
        Ok(PgDdlMatcher {
            empty_namespace: rule.empty_namespace,
            desc_regex: desc_regex,
            tag_regex: tag_regex,
            filename_template: rule.filename.clone(),
        })
    }

    fn matches(
        &self,
        handlebars: &Handlebars,
        entry: &TocEntry,
    ) -> Result<Option<String>, handlebars::RenderError> {
        if self.empty_namespace != entry.namespace.is_empty() {
            return Ok(None);
        }
        if let Some(desc_captures) = self.desc_regex.captures(&entry.desc) {
            if let Some(tag_captures) = self.tag_regex.captures(&entry.tag) {
                let data = TemplateData {
                    namespace: entry.namespace.clone(),
                    desc_parts: desc_captures
                        .iter()
                        .map(|m| match m {
                            Some(m) => m.as_str().to_string(),
                            None => String::new(),
                        })
                        .collect(),
                    tag_parts: tag_captures
                        .iter()
                        .map(|m| match m {
                            Some(m) => m.as_str().to_string(),
                            None => String::new(),
                        })
                        .collect(),
                };
                return Ok(Some(handlebars.render(&self.filename_template, &data)?));
            }
        }
        Ok(None)
    }
}

#[derive(Debug)]
pub struct PgDdlConfig<'a> {
    handlebars: Handlebars<'a>,
    matchers: Vec<PgDdlMatcher>,
}

impl<'a> PgDdlConfig<'a> {
    pub fn new() -> Self {
        PgDdlConfig {
            handlebars: Handlebars::new(),
            matchers: Vec::new(),
        }
    }

    pub fn set_ruleset_from_str(&mut self, ruleset: &str) -> Result<(), serde_yaml::Error> {
        let ruleset: Vec<PgDdlRule> = serde_yaml::from_str(ruleset)?;
        self.matchers.clear();
        self.push_ruleset(&ruleset);
        Ok(())
    }

    pub fn push_ruleset(&mut self, ruleset: &Vec<PgDdlRule>) {
        for rule in ruleset.iter() {
            match PgDdlMatcher::new(&mut self.handlebars, rule) {
                Ok(matcher) => self.matchers.push(matcher),
                Err(e) => eprintln!("Error compiling regex: {}", e),
            }
        }
    }

    pub fn gen_filename(&self, entry: &TocEntry) -> Option<String> {
        for matcher in self.matchers.iter() {
            match matcher.matches(&self.handlebars, entry) {
                Ok(Some(filename)) => return Some(filename),
                Ok(None) => (),
                Err(e) => {
                    eprintln!("Error rendering template: {}", e);
                }
            }
        }
        None
    }

    pub fn analyze_pgarchive(
        &self,
        archive: Archive,
        flatten_folder: i8,
    ) -> HashMap<String, String> {
        let mut sql_files: HashMap<String, String> = HashMap::new();
        for entry in archive.toc_entries {
            let filename = self
                .gen_filename(&entry)
                .unwrap_or("unclassified.sql".to_string());
            let filename = if flatten_folder > 0 {
                filename.replacen("/", "-", flatten_folder as usize)
            } else {
                filename
            };
            let e = sql_files
                .entry(filename.clone())
                .or_insert("-- Auto-generated by dbmigrator. DO NOT EDIT!\n".to_string());
            e.push_str(
                format!(
                    "-- Name: {}; Type: {}; Schema: {}; Owner: {}\n",
                    entry.tag,
                    entry.desc,
                    if entry.namespace.is_empty() {
                        "-"
                    } else {
                        &entry.namespace
                    },
                    entry.owner
                )
                .as_str(),
            );
            if !entry.drop_stmt.is_empty() {
                e.push_str("-- ");
                e.push_str(entry.drop_stmt.as_str());
            }
            if entry.desc == "ACL" || entry.desc == "DEFAULT ACL" {
                e.push_str(&sort_acl_grants(&entry.defn));
            } else {
                e.push_str(entry.defn.as_str());
            }
            if !entry.copy_stmt.is_empty() {
                e.push_str("-- ");
                e.push_str(entry.copy_stmt.as_str());
            }
            e.push_str("\n");
        }
        sql_files
    }
}

static GRANT_REGEX: LazyLock<regex::Regex> = LazyLock::new(|| {
    let ident = r#"(?:[^\s"]+|"(?:[^"]|"")*")"#;
    regex::Regex::new(&format!(
        r"^(?:ALTER DEFAULT PRIVILEGES (?:FOR ROLE {ident} )?(?:IN SCHEMA {ident} )?)?GRANT "
    ))
    .unwrap()
});

/// Sorts each run of consecutive GRANT statements in the definition of an ACL entry.
///
/// PostgreSQL orders ACL arrays by role OID, so pg_dump's statement order differs between
/// clusters. Statements other than GRANT (REVOKE, SET/RESET SESSION AUTHORIZATION) keep their
/// place and split the runs. Definitions with multi-line statements are left as they are.
fn sort_acl_grants(defn: &str) -> String {
    let body = defn.strip_suffix('\n').unwrap_or(defn);
    let mut lines: Vec<&str> = body.split('\n').collect();
    // An odd number of quotes means the line ends inside a quoted identifier.
    if lines
        .iter()
        .any(|line| !line.ends_with(';') || line.matches('"').count() % 2 != 0)
    {
        return defn.to_string();
    }
    for run in lines.split_mut(|line| !GRANT_REGEX.is_match(line)) {
        run.sort_unstable();
    }
    let mut sorted = lines.join("\n");
    sorted.push_str(&defn[body.len()..]);
    sorted
}

#[cfg(test)]
mod tests {
    use super::sort_acl_grants;

    #[test]
    fn sorts_grants_after_revoke() {
        let defn = "REVOKE ALL ON FUNCTION s.f() FROM PUBLIC;\n\
                    GRANT ALL ON FUNCTION s.f() TO rw;\n\
                    GRANT ALL ON FUNCTION s.f() TO auth;\n\
                    GRANT ALL ON FUNCTION s.f() TO r;\n";
        assert_eq!(
            sort_acl_grants(defn),
            "REVOKE ALL ON FUNCTION s.f() FROM PUBLIC;\n\
             GRANT ALL ON FUNCTION s.f() TO auth;\n\
             GRANT ALL ON FUNCTION s.f() TO r;\n\
             GRANT ALL ON FUNCTION s.f() TO rw;\n"
        );
    }

    #[test]
    fn sorts_default_privileges() {
        let defn = "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA s GRANT SELECT ON TABLES TO rw;\n\
                    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA s GRANT SELECT ON TABLES TO r;\n";
        assert_eq!(
            sort_acl_grants(defn),
            "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA s GRANT SELECT ON TABLES TO r;\n\
             ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA s GRANT SELECT ON TABLES TO rw;\n"
        );
    }

    #[test]
    fn keeps_revoke_in_place() {
        let defn = "ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" REVOKE GRANT OPTION FOR ALL ON TABLES FROM b;\n\
                    ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" GRANT SELECT ON TABLES TO b;\n\
                    ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" GRANT SELECT ON TABLES TO a;\n";
        assert_eq!(
            sort_acl_grants(defn),
            "ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" REVOKE GRANT OPTION FOR ALL ON TABLES FROM b;\n\
             ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" GRANT SELECT ON TABLES TO a;\n\
             ALTER DEFAULT PRIVILEGES FOR ROLE \"Some Role\" GRANT SELECT ON TABLES TO b;\n"
        );
    }

    #[test]
    fn leaves_grants_by_other_grantors_unsorted() {
        // pg_dump wraps each grant made by a role other than the owner in its own block.
        let defn = "GRANT SELECT ON TABLE s.t TO b WITH GRANT OPTION;\n\
                    GRANT SELECT ON TABLE s.t TO a;\n\
                    SET SESSION AUTHORIZATION b;\n\
                    GRANT SELECT ON TABLE s.t TO d;\n\
                    RESET SESSION AUTHORIZATION;\n\
                    SET SESSION AUTHORIZATION b;\n\
                    GRANT SELECT ON TABLE s.t TO c;\n\
                    RESET SESSION AUTHORIZATION;\n";
        assert_eq!(
            sort_acl_grants(defn),
            "GRANT SELECT ON TABLE s.t TO a;\n\
             GRANT SELECT ON TABLE s.t TO b WITH GRANT OPTION;\n\
             SET SESSION AUTHORIZATION b;\n\
             GRANT SELECT ON TABLE s.t TO d;\n\
             RESET SESSION AUTHORIZATION;\n\
             SET SESSION AUTHORIZATION b;\n\
             GRANT SELECT ON TABLE s.t TO c;\n\
             RESET SESSION AUTHORIZATION;\n"
        );
    }

    #[test]
    fn leaves_multi_line_statements_unchanged() {
        let defn = "GRANT SELECT ON TABLE s.\"multi\nline\" TO b;\nGRANT SELECT ON TABLE s.t TO a;\n";
        assert_eq!(sort_acl_grants(defn), defn);
        let defn = "GRANT SELECT ON TABLE s.t TO z;\nGRANT SELECT ON TABLE s.t TO \"a;\nb\";\n";
        assert_eq!(sort_acl_grants(defn), defn);
    }
}
